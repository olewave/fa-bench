"""Generate the tech report's LaTeX result tables from the SAME source as the
markdown ones.

WHY GENERATED. docs/tech_report/fa-bench/v1/tables/*.tex were hand-written, so
the paper's numbers and the site's numbers were two independent transcriptions
of one scoring run and could drift silently. These read summary/ via
evals.report_parse.collect() -- never recomputed here -- so the paper
cannot disagree with summary/.

WHAT IS **NOT** GENERATED, and why:

* tables/bridge.tex needs DUAL-PROTOCOL numbers (our matcher vs the bridge to
  the original evaluation code). The current summary/ tree carries no protocol
  tag and no mfa_paper cells, so those deltas are not derivable from it.
  Regenerating it from what is on disk would silently republish fabench-protocol
  numbers under a "bridge" heading. Left hand-written; rerun the dual-protocol
  scoring and revisit.
* tables/aligners.tex is curated provenance -- training corpora and the
  train/test overlap flag. That is knowledge about each system, not a scorer
  output, and the paper's four-system scope is deliberate (it is the Table 5
  reproduction, not the full benchmark).

Usage:  gen_tex_tables.py [--out <tables dir>] [--check]
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from evals.report_parse import _mae_or_inf, collect, subsets_of
from evals.update_public_tables import (
    FAMILY_LABEL,
    FLAGGED,
    SUPPRESS_PUBLIC,
    disp,
    fam,
    group_key,
)

DEFAULT_OUT = (ROOT.parent / "docs" / "tech_report" / "fa-bench" / "v1"
               / "tables")

#: paper scope for the register table -- the four systems the reproduction
#: covers, in the order the prose discusses them
REGISTER_SYSTEMS = ["maps", "mfa", "charsiu", "bfa"]

BANNER = ("% GENERATED by evals/gen_tex_tables.py -- do not edit by hand.\n"
          "% Source: summary/en/<corpus>/<subset>/report.md via\n"
          "% evals.report_parse.collect(). Regenerate after rescore.\n")


def tex(s) -> str:
    """Escape a value for LaTeX text."""
    s = str(s)
    for a, b in (("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"),
                 ("$", r"\$"), ("#", r"\#"), ("_", r"\_"), ("{", r"\{"),
                 ("}", r"\}"), ("~", r"\textasciitilde{}"),
                 ("^", r"\textasciicircum{}")):
        s = s.replace(a, b)
    # the site marks caveated rows with a warning glyph; pdflatex has no such
    # character, so it becomes a dagger and the caption carries the meaning
    return s.replace("⚠", r"$^{\dagger}$").replace("—", "--")


def _name(tool: str) -> str:
    """Display name plus the caveat marker the captions explain."""
    return disp(tool) + ("\u26a0" if tool in FLAGGED else "")


def _num(v):
    try:
        return float(str(v).split(" [")[0].rstrip("%"))
    except (TypeError, ValueError):
        return None


def _cell(v) -> str:
    return "--" if v in (None, "", "—") else tex(v)


def _rows(bysub, sub):
    return [r for r in bysub.get(sub, [])
            if _mae_or_inf(r) != float("inf")
            and r["aligner"] not in SUPPRESS_PUBLIC]


def _primary_test(bysub) -> str | None:
    """The split the paper quotes as 'test' for a corpus."""
    for s in subsets_of(bysub):
        if "test" in s and _rows(bysub, s):
            return s
    return None


# --------------------------------------------------------------------------
# results.tex -- the concise comparison, dev vs test, grouped by \multicolumn
# --------------------------------------------------------------------------
def _sdi(r) -> str:
    """Sub/Del/Ins in one cell -- which KIND of error, not just how much."""
    v = [r.get(k) for k in ("sub_pct", "del_pct", "ins_pct")]
    if any(x in (None, "", "\u2014") for x in v):
        return ""
    return "/".join(str(x) for x in v)


METRICS = [("MAE (ms)", lambda r: r["mae"].split(" [")[0]),
           ("S/D/I (\\%)", _sdi),
           ("PER (\\%)", lambda r: r.get("per")),
           ("Pre", lambda r: r.get("bnd_p")),
           ("Rec", lambda r: r.get("bnd_r")),
           ("F1", lambda r: r.get("bnd_f1"))]


def results_table(corpus: str, bysub: dict) -> str:
    test = _primary_test(bysub)
    subs = [s for s in ("dev", test) if s and _rows(bysub, s)]
    if not subs:
        return ""
    n = len(METRICS)

    per_sys: dict[str, dict] = {}
    for s in subs:
        for r in _rows(bysub, s):
            per_sys.setdefault(r["aligner"], {})[s] = r

    def rank(name):
        for s in subs:
            r = per_sys[name].get(s)
            if r is not None:
                return group_key(name, _mae_or_inf(r))
        return group_key(name, None)

    # column spec: two left-aligned label columns, then n right-aligned per split
    spec = "@{}ll" + " ".join("r" * n for _ in subs) + "@{}"
    L = [BANNER,
         r"\begin{table*}[t]\centering\small",
         r"\caption{Phone-level alignment on " + tex(corpus.upper())
         + r". MAE on the matched path (label-paired); PER is the edit cost of "
           r"that path; Pre/Rec/F1 are boundary detection at a 20\,ms "
           r"tolerance (time-paired, label-agnostic). "
           r"$^{\dagger}$ marks a system whose training data overlaps a "
           r"benchmark corpus.}",
         r"\label{tab:results-" + corpus + "}",
         r"\begin{tabular}{" + spec + "}",
         r"\toprule"]

    # spanning split header + cmidrules underneath each group
    head = " & " * 2 + " & ".join(
        rf"\multicolumn{{{n}}}{{c}}{{{tex(s)}}}" for s in subs) + r" \\"
    rules = "".join(rf"\cmidrule(lr){{{3 + i * n}-{2 + (i + 1) * n}}}"
                    for i in range(len(subs)))
    L += [head, rules,
          "family & system & "
          + " & ".join(m for _ in subs for m, _g in METRICS) + r" \\",
          r"\midrule"]

    for name in sorted(per_sys, key=rank):
        cells = [_cell(get(per_sys[name][s])) if s in per_sys[name] else "--"
                 for s in subs for _m, get in METRICS]
        L.append(f"{tex(FAMILY_LABEL.get(fam(name), fam(name)))} & "
                 f"{tex(_name(name))} & " + " & ".join(cells) + r" \\")

    L += [r"\bottomrule", r"\end{tabular}", r"\end{table*}", ""]
    return "\n".join(L)


# --------------------------------------------------------------------------
# register.tex -- TIMIT vs Buckeye transfer for the paper's four systems
# --------------------------------------------------------------------------
def register_table(data: dict) -> str:
    def pick(corpus):
        """The split with the BEST COVERAGE of the paper's four systems.

        Not simply the first non-empty one: a sweep in flight can leave a
        split holding a single freshly-rescored row, and picking that yields a
        table with no body at all.
        """
        bysub = data.get(corpus, {})
        best, best_n, best_map = None, -1, {}
        for s in subsets_of(bysub):
            m = {r["aligner"]: r for r in _rows(bysub, s)}
            n = sum(1 for x in REGISTER_SYSTEMS if x in m)
            if n > best_n:
                best, best_n, best_map = s, n, m
        return best, best_map

    t_sub, t = pick("timit")
    b_sub, b = pick("buckeye")
    if not t or not b:
        return ""

    L = [BANNER,
         r"\begin{table}[t]\centering\small",
         r"\caption{Register transfer and retention. Phone MAE in ms; "
         r"$\Delta$ is the cost of moving from read (TIMIT " + tex(t_sub)
         + r") to spontaneous speech (Buckeye " + tex(b_sub)
         + r"). ARR is the fraction of gold boundaries receiving a match, "
           r"given as the range across the two corpora.}",
         r"\label{tab:register}",
         r"\begin{tabular}{@{}lrrrr@{}}",
         r"\toprule",
         r"system & TIMIT & Buckeye & $\Delta$ & ARR \\",
         r"\midrule"]

    body, missing = [], []
    for name in REGISTER_SYSTEMS:
        rt, rb = t.get(name), b.get(name)
        if not rt or not rb:
            missing.append(name)
            continue
        mt, mb = _num(rt.get("mae")), _num(rb.get("mae"))
        at, ab = _num(rt.get("arr")), _num(rb.get("arr"))
        d = (f"${mb - mt:+.2f}$" if mt is not None and mb is not None
             else "--")
        arr = (f"{min(at, ab):.0f}--{max(at, ab):.0f}"
               if at is not None and ab is not None else "--")
        body.append((mb - mt if mt is not None and mb is not None
                     else float("inf"),
                     f"{tex(_name(name))} & {mt:.2f} & {mb:.2f} & {d} & {arr}"
                     + r" \\"))
    # smallest transfer penalty last -- same "better sits lower" rule as the
    # markdown tables, so the eye lands on the system that retains best
    if not body:
        return ""          # an empty tabular is worse than no file
    L += [ln for _k, ln in sorted(body, key=lambda x: -x[0])]
    L += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    if missing:
        L.insert(1, "% NOT PRESENT in summary/: " + ", ".join(missing))
    return "\n".join(L)


def prose_coupling(data: dict, out: Path) -> list[str]:
    """Numbers the PROSE quotes that this table also derives.

    sections/04_results.tex states the register collapse and the retention
    range inline ("collapses by 11.6 ms", "Retention varies from 67 to 82%").
    Regenerating register.tex without touching those sentences makes the paper
    contradict its own table, which is worse than a stale table -- a reader
    checks the number against the text, not against summary/. So the generator
    recomputes them and reports what the prose would have to say.
    """
    sect = out.parent / "sections"
    if not sect.is_dir():
        return []
    reg = register_table(data)
    if not reg:
        return []
    deltas, arrs = [], []
    for ln in reg.splitlines():
        if "$+" in ln or "$-" in ln:
            parts = [p.strip() for p in ln.split("&")]
            try:
                deltas.append((parts[0], float(parts[3].strip("$ \\")
                                               .replace("+", ""))))
                lo, hi = parts[4].split(r"\\")[0].strip().split("--")
                arrs += [float(lo), float(hi)]
            except (IndexError, ValueError):
                continue
    if not deltas:
        return []
    worst = max(deltas, key=lambda x: x[1])
    best = min(deltas, key=lambda x: x[1])
    return [
        f"largest register collapse : {worst[0]} {worst[1]:+.1f} ms",
        f"most register-robust      : {best[0]} {best[1]:+.1f} ms",
        f"retention (ARR) range     : {min(arrs):.0f}--{max(arrs):.0f}%",
        (f"cross-check against prose in {sect.relative_to(out.parent.parent)}"
        "/04_results.tex"),
    ]


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--out", default=str(DEFAULT_OUT))
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if any file would change (for CI)")
    a = ap.parse_args(argv)

    out = Path(a.out)
    if not out.is_dir():
        print(f"  no tables dir at {out}", file=sys.stderr)
        return 1

    data = collect()
    if not data:
        print("  no reports found; run rescore_all.sh first", file=sys.stderr)
        return 1

    files = {}
    for corpus in sorted(data):
        body = results_table(corpus, data[corpus])
        if body:
            files[f"results_{corpus}.tex"] = body
    reg = register_table(data)
    if reg:
        files["register.tex"] = reg

    stale = []
    for name, body in files.items():
        p = out / name
        old = p.read_text() if p.is_file() else None
        if old == body:
            print(f"  unchanged {name}")
            continue
        stale.append(name)
        if not a.check:
            p.write_text(body)
            print(f"  wrote {name} ({body.count(chr(10))} lines)")

    if a.check and stale:
        print(f"  STALE: {', '.join(stale)}", file=sys.stderr)
        return 1
    if not a.check:
        print("  NOT generated (see module docstring): bridge.tex, aligners.tex")
        coupled = prose_coupling(data, out)
        if coupled:
            print("\n  PROSE QUOTES THESE -- update 04_results.tex to match:")
            for ln in coupled:
                print(f"    {ln}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
