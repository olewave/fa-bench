"""Publish a dated snapshot of the result pages.

    evals/publish_records.py                 # snapshot for the current month
    evals/publish_records.py --month 202608  # or a named one
    evals/publish_records.py --check         # exit 1 if it would change anything

WHY DATED SNAPSHOTS. `summary/` is script output -- regenerated by every
rescore, and gitignored for that reason. What gets published is a deliberate act
by a person: a monthly snapshot of the curated pages, with the numbers as they
stood. A reader lands on a fixed thing that will not shift under them, and a
citation can name the month.

    records/aligners/en/
        202608/timit/README.md  Details.md
        202608/buckeye/README.md  Details.md
        latest -> 202608

CARRYING PROSE FORWARD. The pages are ~70% hand-written analysis with generated
tables between BEGIN/END markers. A new month therefore starts as a COPY of the
previous snapshot, and only the marked blocks are refilled -- so last month's
interpretation survives and only the numbers move. Edit the prose in the current
month's directory; it is carried into the next.

`latest` is a relative symlink, so it survives a clone and a move.
"""
from __future__ import annotations

import argparse
import re
import shutil
import subprocess
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RECORDS = ROOT / "records" / "aligners" / "en"
LATEST = RECORDS / "latest"


def month_dirs() -> list[str]:
    """Existing snapshots, oldest first. `latest` is a symlink, not one."""
    return sorted(p.name for p in RECORDS.glob("[0-9]" * 6) if p.is_dir())


def seed(target: Path) -> str:
    """Create `target`, carrying the previous snapshot's prose forward.

    Returns a one-line description of where the content came from, because
    "seeded from 202607" and "started empty" mean very different things when
    reviewing the diff.
    """
    if target.exists():
        return f"{target.name} exists -- refilling its blocks"
    prev = month_dirs()
    if prev:
        src = RECORDS / prev[-1]
        shutil.copytree(src, target)
        return f"{target.name} seeded from {src.name} (prose carried forward)"
    target.mkdir(parents=True)
    return f"{target.name} created empty -- no earlier snapshot to carry"


def point_latest(target: Path) -> None:
    """Repoint `latest` at `target`, relatively."""
    if LATEST.is_symlink() or LATEST.exists():
        LATEST.unlink()
    LATEST.symlink_to(target.name)


def retarget_readme(month: str) -> None:
    """Point the root README's records links at the new snapshot.

    The README links name a concrete month, not `latest`: GitHub's web UI
    renders a symlinked directory as a text file rather than traversing it,
    so a `latest/...` link 404s on the site even though it works in a clone.
    The price of concrete links is that they go stale on publish -- which is
    why repointing them is part of publishing, not a thing to remember.
    """
    readme = ROOT / "README.md"
    text = readme.read_text()
    new = re.sub(r"records/aligners/en/\d{6}/", f"records/aligners/en/{month}/", text)
    if new != text:
        readme.write_text(new)
        print(f"  README records links -> {month}")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--month", default=date.today().strftime("%Y%m"),  # noqa: DTZ011  local month is the intent
                    help="snapshot to write (YYYYMM); default is this month")
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if the snapshot would change (for CI)")
    a = ap.parse_args(argv)

    if not (len(a.month) == 6 and a.month.isdigit()):
        print(f"--month must be YYYYMM, got {a.month!r}", file=sys.stderr)
        return 2

    target = RECORDS / a.month
    if a.check:
        if not target.is_dir():
            print(f"no snapshot for {a.month}", file=sys.stderr)
            return 1
    else:
        print(" ", seed(target))

    # The provenance block is written by a DIFFERENT script -- it reads package
    # versions, not scores -- so publishing must call both or the versions in a
    # snapshot silently keep whatever they had. That is not hypothetical: an
    # olign version fix landed in gen_provenance.py and never reached the page.
    if not a.check:
        rc = subprocess.call([sys.executable, str(ROOT / "evals" / "gen_provenance.py"),
                              "--offline", "--doc", str(target / "README.md")], cwd=ROOT)
        if rc != 0:
            return rc

    # Fill the generated blocks from the CURRENT numbers in summary/.
    cmd = [sys.executable, str(ROOT / "evals" / "update_public_tables.py"),
           "--records-dir", str(target)]
    if a.check:
        cmd.append("--check")
    rc = subprocess.call(cmd, cwd=ROOT)
    if rc != 0:
        return rc

    if not a.check:
        point_latest(target)
        print(f"  latest -> {a.month}")
        retarget_readme(a.month)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
